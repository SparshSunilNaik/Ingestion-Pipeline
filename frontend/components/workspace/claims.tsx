"use client";

import { Sparkles } from "lucide-react";
import type { Claim, Section } from "@/lib/api";
import { Badge, BasisBadge, cn } from "@/components/ui";
import { EvidenceList } from "@/components/workspace/nav";

export function ClaimItem({ claim, dense }: { claim: Claim; dense?: boolean }) {
  return (
    <li className={cn("group rounded-md border border-transparent", dense ? "py-1" : "px-2 py-1.5 hover:border-line hover:bg-panel-2")}>
      <div className="flex items-start gap-2">
        <BasisBadge basis={claim.basis} />
        <div className="min-w-0 flex-1">
          <p className={cn("text-[13px] leading-relaxed", claim.basis === "unsupported" && "text-fg-3 line-through decoration-bad/50")}>{claim.statement}</p>
          {(claim.evidence_ids.length > 0 || claim.note) && (
            <div className="mt-1 flex flex-wrap items-center gap-1.5">
              <EvidenceList ids={claim.evidence_ids} />
              {claim.note && <span className="text-[11.5px] text-fg-3">{claim.note}</span>}
            </div>
          )}
        </div>
      </div>
    </li>
  );
}

export function ClaimList({ claims, dense, empty = "Nothing determined." }: { claims: Claim[]; dense?: boolean; empty?: string }) {
  if (!claims.length) return <p className="text-[12.5px] text-fg-3">{empty}</p>;
  return (
    <ul className={cn(dense ? "space-y-0.5" : "space-y-0.5")}>
      {claims.map((c, i) => (
        <ClaimItem key={i} claim={c} dense={dense} />
      ))}
    </ul>
  );
}

export function AiLabel({ model }: { model?: string | null }) {
  return (
    <Badge tone="info" title="Generated by an AI model from cited evidence; each claim's evidence was re-verified by the backend.">
      <Sparkles className="h-3 w-3" aria-hidden /> AI interpretation{model ? ` · ${model}` : ""}
    </Badge>
  );
}

export function findSection(sections: Section[] | undefined, title: string): Claim[] {
  return sections?.find((s) => s.title === title)?.claims ?? [];
}
